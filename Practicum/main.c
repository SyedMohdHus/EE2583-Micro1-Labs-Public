void main(void) {
    char Sout[20];          // buffer for sprintf
    unsigned int Pot;

    Pin_Clock_Config();     // 4 MHz clock and all pins
    A2D_Init(11);           // POT on AN11 (RB5)
    i2c_Init();             // I2C master 100 kHz

    SSD1306_Init();         // init OLED
    SSD1306_Fill(0);        // clear display

    // Splash screen
    SSD1306_Image(Logo, 1); // 1 = light on dark
    __delay_ms(2000);
    SSD1306_Fill(0);

    // Challenge 1/2: group name in the big font for 2 s, then erase
    SSD1306_Out16(2, 3, GROUP_NAME, 1);
    __delay_ms(2000);
    SSD1306_Fill(0);

    // Challenge 3: show the POT value forever
    SSD1306_Out8(0, 0, "Micro1 Practicum", 1);
    while (1) {
        Pot = Get_A2D_Result();             // 0 to 1023
        sprintf(Sout, "Pot=%u    ", Pot);   // trailing spaces wipe old digits
        SSD1306_Out16(3, 2, Sout, 1);       // rows 3-4, starting at column 2
        __delay_ms(100);
    }
}

void Pin_Clock_Config(void) {
    OSCCON = 0x68;  // HFINTOSC, no PLL, 4 MHz
    LATA   = 0x24;
    LATB   = 0x00;
    LATC   = 0x40;
    TRISA  = 0x1B;  // RA5 and RA2 outputs
    TRISB  = 0xF0;  // all B's inputs
    TRISC  = 0xBF;  // only RC6 is output
    ANSELA = 0x00;  // all digital
    ANSELB = 0x20;  // only RB5 analog
    ANSELC = 0x0C;  // RC3 and RC2 analog, rest digital
    LATA   = 0x24;  // Green and Blue off
    LATB   = 0x00;
    LATC   = 0x40;  // Red off
}

void A2D_Init(unsigned int Chanel) {
    ADCON1 = 0xC0;                  // right justified, Fosc/4
    ADCON0 = (Chanel << 2) | 1;     // select channel, ADC on
}

unsigned int Get_A2D_Result(void) {
    int j;
    for (j = 0; j < 0x02; j++) continue;    // let the sampling cap charge
    ADGO = 1;                               // start conversion
    while (ADGO) continue;
    return ((ADRESH << 8) + ADRESL);
}
